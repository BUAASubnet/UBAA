#!/usr/bin/env python3
"""批量读取 Git index，分别检查 index 与工作树的结构棘轮。"""
from collections import Counter, defaultdict
from pathlib import Path, PurePosixPath
import re
import subprocess
import sys


EXTENSIONS = {
    '.rs', '.dart', '.kt', '.kts', '.ets', '.ts', '.tsx', '.js', '.cjs',
    '.py', '.java', '.swift', '.m', '.mm', '.c', '.cc', '.cpp', '.h', '.hpp', '.sh',
}
GENERATED_HEADERS = (
    b'This file is automatically generated, so please do not edit it.',
    b'@generated by `flutter_rust_bridge`@',
)


def git(root, *args, payload=None):
    result = subprocess.run(['git', '-C', str(root), *args], input=payload,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=False)
    if result.returncode:
        raise ValueError(f'Git {args[0]} 失败，退出码 {result.returncode}')
    return result.stdout


def supported(path, errors):
    if '\n' in path or '\t' in path:
        errors.append(f'源码路径包含不支持的换行或制表符：{path}')
        return False
    return (path.endswith(tuple(EXTENSIONS))
            and not path.startswith('packages/ubaa_bindings/cargokit/'))


def record(path, content, directories, violations):
    generated_path = (path == 'crates/ubaa_flutter_bridge/src/frb_generated.rs'
                      or path.startswith('packages/ubaa_bindings/lib/src/rust/'))
    if generated_path and all(marker in b'\n'.join(content.split(b'\n', 8)[:8])
                              for marker in GENERATED_HEADERS):
        return
    directories[str(PurePosixPath(path).parent)] += 1
    # 与 awk 的 NR 一致：最后一行没有换行符时也计一行，空文件计零行。
    lines = content.count(b'\n') + int(bool(content) and not content.endswith(b'\n'))
    if lines > 1000:
        violations.add(('file', path, str(lines)))


def index_entries(root, errors):
    entries = []
    for entry in git(root, 'ls-files', '--stage', '-z', '--cached').split(b'\0'):
        if not entry:
            continue
        metadata, path_bytes = entry.split(b'\t', 1)
        mode, oid, stage = metadata.decode('ascii').split()
        if stage != '0':
            raise ValueError('仓库存在未解决的 index 冲突，无法建立结构快照')
        path = path_bytes.decode('utf-8', errors='surrogateescape')
        if not supported(path, errors):
            continue
        if mode == '120000':
            errors.append(f'源码符号链接不允许：{path}')
        elif mode not in {'100644', '100755'}:
            errors.append(f'源码 index mode 不受支持（{mode}）：{path}')
        else:
            entries.append((path, oid))
    return entries


def index_blobs(root, entries):
    # 按对象读取，避免每个文件分别执行 ls-files/show；路径不进入行分隔协议。
    oids = list(dict.fromkeys(oid for _, oid in entries))
    if not oids:
        return {}
    output = git(root, 'cat-file', '--batch', payload=('\n'.join(oids) + '\n').encode('ascii'))
    cursor, blobs = 0, {}
    for oid in oids:
        end = output.find(b'\n', cursor)
        header = output[cursor:end].split()
        if (end < 0 or len(header) != 3 or header[0] != oid.encode('ascii')
                or header[1] != b'blob' or not header[2].isdigit()):
            raise ValueError('Git cat-file 未返回完整的 index blob')
        size = int(header[2])
        start, cursor = end + 1, end + 2 + size
        if cursor > len(output) or output[cursor - 1:cursor] != b'\n':
            raise ValueError('Git cat-file 返回的 index blob 被截断')
        blobs[oid] = output[start:cursor - 1]
    if cursor != len(output):
        raise ValueError('Git cat-file 返回了多余的 index blob 数据')
    return blobs


def snapshots(root, errors):
    violations = set()
    index_directories, worktree_directories = Counter(), Counter()
    entries = index_entries(root, errors)
    blobs = index_blobs(root, entries)
    for path, oid in entries:
        record(path, blobs[oid], index_directories, violations)
    paths = git(root, 'ls-files', '-z', '--cached', '--others', '--exclude-standard')
    for path_bytes in paths.split(b'\0'):
        if not path_bytes:
            continue
        path = path_bytes.decode('utf-8', errors='surrogateescape')
        if not supported(path, errors):
            continue
        absolute = root / path
        if absolute.is_symlink():
            errors.append(f'源码符号链接不允许：{path}')
        elif absolute.is_file():
            record(path, absolute.read_bytes(), worktree_directories, violations)
    for directories in (index_directories, worktree_directories):
        violations.update(('dir', path, str(count)) for path, count in directories.items()
                          if count > 16)
    return violations


def baseline(root, errors):
    path = root / 'scripts/layout-baseline.txt'
    if not path.is_file():
        raise ValueError('缺少 scripts/layout-baseline.txt')
    entries, keys = set(), set()
    for line in path.read_bytes().decode('utf-8', errors='surrogateescape').split('\n'):
        if not line or line.startswith('#'):
            continue
        if line.count('\t') != 2:
            errors.append(f'baseline 必须恰有三列：{line}')
            continue
        kind, relative, count = line.split('\t')
        if kind not in {'file', 'dir'}:
            errors.append(f'baseline kind 未知（{kind}）：{relative}')
            continue
        if (not relative or relative.startswith('/')
                or any(part in {'..', '.', ''} for part in relative.split('/'))):
            errors.append(f'baseline 路径必须是仓库内规范相对路径：{relative}')
            continue
        if not re.fullmatch('[0-9]+', count) or int(count) <= 0:
            errors.append(f'baseline 数量必须是正整数：{relative}')
            continue
        key = (kind, relative)
        if key in keys:
            errors.append(f'baseline 项重复：{relative}')
            continue
        keys.add(key)
        entries.add((kind, relative, count))
        target = root / relative
        if kind == 'file' and not (target.exists() or target.is_symlink()):
            errors.append(f'baseline 文件不存在：{relative}')
        elif kind == 'dir' and not target.is_dir():
            errors.append(f'baseline 目录不存在：{relative}')
    return entries


def compare(entries, violations, errors):
    counts = defaultdict(set)
    for kind, path, count in violations:
        counts[kind, path].add(count)
    for kind, path, expected in sorted(entries):
        actual = counts[kind, path]
        if not actual:
            errors.append(f'baseline 项已不存在或已修复：{path}')
        for count in sorted(actual):
            if count != expected:
                errors.append(f'baseline 数量变化（登记 {expected}，当前 {count}）：{path}')
    for kind, path, count in sorted(violations - entries):
        errors.append(f'发现未登记或数量变化的结构违例（{kind}，{count}）：{path}')


def main(root):
    errors = []
    entries = baseline(root, errors)
    violations = snapshots(root, errors)
    # 保留 Dart part 聚合规模、归属和依赖环检查，不能只统计单个物理文件。
    module_checker = root / 'scripts/check/module_graph.py'
    if module_checker.is_file():
        if subprocess.run([sys.executable, str(module_checker)], check=False).returncode:
            errors.append('Dart library 聚合检查失败')
    compare(entries, violations, errors)
    for error in errors:
        print(f'layout check: {error}', file=sys.stderr)
    if errors:
        raise ValueError(f'layout check failed: {len(errors)} 个问题')
    print(f'layout check passed: {len(violations)} 个精确 baseline 违例')


if __name__ == '__main__':
    try:
        main(Path(sys.argv[1]))
    except (OSError, ValueError) as error:
        raise SystemExit(f'layout check: {error}') from error
